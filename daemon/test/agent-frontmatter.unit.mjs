// ─── Frontmatter reader (test scaffolding, NOT the logic under test) ──────
// `.claude/agents/*.md` is generated by the Covenant compiler (`cov build`), so its
// frontmatter is YAML with quoted scalars (`color: "blue"`), block lists
// (`skills:` then `  - name`), and four `#` header lines. The shared reader lives in
// ./fixtures/frontmatter-yaml.mjs (pair-programmer #73); it is line-oriented on purpose,
// so the strict guard below can still refuse `max_turns : 5`, and it is cross-checked
// against the `yaml` package in "reader fidelity" below.

function makeTempDir(prefix) {
  return mkdtempSync(join(tmpdir(), prefix));
}

// ─── Real, filesystem-derived agent set ────────────────────────────────────
// enumerateAgentSources() is the REAL generator function (Phase G export),
// driven against the real .claude/agents/ tree. This is also, incidentally,
// a live proof that the real tree has no basename collision today (it would
// throw here if it did).
const realAgentSources = enumerateAgentSources(CLAUDE_AGENTS_DIR);
const realAgentRecords = realAgentSources.map(({ file, sourcePath }) => {
  const base = file.replace(/\.md$/, "");
  // `parsed` carries data / lists / keys / comments / malformed / indented.
  return { base, sourcePath, ...readFrontmatterFile(sourcePath) };
});
const realAgentBasenames = new Set(realAgentRecords.map((r) => r.base));

function setDiff(a, b) {
  return [...a].filter((x) => !b.has(x)).sort();
}

// ═══════════════════════════════════════════════════════════════════════
