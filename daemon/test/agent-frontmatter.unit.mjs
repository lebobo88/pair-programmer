// Reader fidelity (pair-programmer #73). The agent files are generated by
// `cov build`. Their frontmatter is valid YAML but quotes some scalars and
// writes `skills:` / `tools:` as block lists. A reader that keeps the quotes
// or reads only the comma form makes every assertion above fail for a reason
// that has nothing to do with the policy it guards (46 false failures).
// ═══════════════════════════════════════════════════════════════════════
describe("reader fidelity: generated YAML reads as the same values the hand-written form did", () => {
  it("a double-quoted scalar equals its unquoted value", () => {
    const quoted = parseFrontmatter('name: a\ncolor: "blue"\n');
    const plain = parseFrontmatter("name: a\ncolor: blue\n");
    assert.equal(quoted.data.color, "blue");
    assert.equal(quoted.data.color, plain.data.color);
    assert.deepEqual(quoted.malformed, []);
  });

  it("a single-quoted scalar equals its unquoted value, and '' is an escaped quote", () => {
    assert.equal(parseFrontmatter("color: 'blue'").data.color, "blue");
    assert.equal(parseFrontmatter("description: 'it''s fine'").data.description, "it's fine");
  });

  it("a quoted scalar keeps the characters that make YAML quote it (colon, hash, escaped quote)", () => {
    const { data, malformed } = parseFrontmatter('description: "Use when: a # b, and \\"c\\" too"');
    assert.equal(data.description, 'Use when: a # b, and "c" too');
    assert.deepEqual(malformed, []);
  });

  it("a block list equals the comma form, as data string, as members and through listMembers()", () => {
    const block = parseFrontmatter("name: a\nskills:\n  - judge-policy\n  - rubric-application\ncolor: blue\n");
    const comma = parseFrontmatter("name: a\nskills: judge-policy, rubric-application\ncolor: blue\n");
    assert.equal(block.data.skills, comma.data.skills);
    assert.deepEqual(block.lists.skills, ["judge-policy", "rubric-application"]);
    assert.deepEqual(listMembers(block, "skills"), listMembers(comma, "skills"));
    assert.deepEqual(block.keys, comma.keys, "a block list must not add or drop top-level keys");
    assert.deepEqual([block.malformed, block.indented], [[], []]);
  });

  it("falsifiability: a block list with a different member is NOT equal to the comma form", () => {
    const block = parseFrontmatter("skills:\n  - judge-policy\n  - rubric-application\n");
    const other = parseFrontmatter("skills: judge-policy, taxonomy-adherence\n");
    assert.notDeepEqual(listMembers(block, "skills"), listMembers(other, "skills"));
  });

  it("quoted block-list members are unquoted", () => {
    const { lists, malformed } = parseFrontmatter('tools:\n  - "Read"\n  - Write\n');
    assert.deepEqual(lists.tools, ["Read", "Write"]);
    assert.deepEqual(malformed, []);
  });

  it("falsifiability: quotes do not leak into the colour check (\"magenta\" stays undocumented, \"blue\" is documented)", () => {
    assert.equal(isDocumentedColor(parseFrontmatter('color: "magenta"').data.color), false);
    assert.equal(isDocumentedColor(parseFrontmatter('color: "blue"').data.color), true);
  });

  it("parseScalar reports (not guesses at) shapes it cannot read faithfully", () => {
    for (const token of ['"open', "'open", '"a" trailing', "{ a: 1 }", "|", ">-", '"\\x41"']) {
      assert.equal(parseScalar(token).ok, false, `${token} must be reported, not read`);
    }
    assert.deepEqual(parseScalar("plain # note"), { ok: true, value: "plain" });
  });

  it("CRLF: raw bytes defeat a naive split, the normalising reader parses them (both directions)", () => {
    const crlf = '---\r\nname: a\r\ncolor: "blue"\r\nskills:\r\n  - x\r\n---\r\nbody\r\n';
    // direction 1: the construct that actually breaks is an explicit "\n" in the pattern.
    assert.equal(crlf.startsWith("---\n"), false, "raw CRLF must fail the naive fence check, or this proof cannot tell a normaliser from a tolerant regex");
    assert.ok(crlf.split("\n").some((l) => l.endsWith("\r")), "a naive split must strand a \\r");
    // direction 2: the real reader handles it.
    const { frontmatter, found } = splitFrontmatter(crlf);
    assert.equal(found, true);
    const parsed = parseFrontmatter(frontmatter);
    assert.equal(parsed.data.color, "blue");
    assert.deepEqual(parsed.lists.skills, ["x"]);
    assert.deepEqual([parsed.malformed, parsed.indented], [[], []]);
  });

  // The independent oracle: the `yaml` package parses the same text. The expected value is
  // never computed by the code under test (no-vacuous-assertions class 3).
  function readerDisagreements(frontmatter) {
    const parsed = parseFrontmatter(frontmatter);
    const oracle = parseYaml(frontmatter) ?? {};
    const out = [];
    for (const key of Object.keys(oracle)) {
      if (!parsed.keys.includes(key)) {
        out.push(`${key}: yaml sees this key, the reader does not`);
        continue;
      }
      const expected = oracle[key];
      if (Array.isArray(expected)) {
        const got = listMembers(parsed, key);
        if (JSON.stringify(got) !== JSON.stringify(expected.map(String))) out.push(`${key}: reader ${JSON.stringify(got)} vs yaml ${JSON.stringify(expected)}`);
      } else {
        const want = expected === null || expected === undefined ? "" : String(expected);
        if (parsed.data[key] !== want) out.push(`${key}: reader ${JSON.stringify(parsed.data[key])} vs yaml ${JSON.stringify(want)}`);
      }
    }
    for (const key of parsed.keys) if (!(key in oracle)) out.push(`${key}: the reader sees this key, yaml does not`);
    return out;
  }

  it("oracle: on every real generated agent the line reader and the yaml package agree on every key and value", () => {
    assert.ok(realAgentRecords.length > 0, "derived zero agents -- the oracle comparison would pass vacuously");
    const disagreements = [];
    for (const r of realAgentRecords) for (const d of readerDisagreements(r.frontmatter)) disagreements.push(`${r.base}: ${d}`);
    assert.deepEqual(disagreements, [], "reader and yaml disagree:\n  " + disagreements.join("\n  "));
  });

  it("non-vacuity: the real tree actually exercises quoted scalars and block lists (the constructs this section exists for)", () => {
    const withQuoted = realAgentRecords.filter((r) => /^\s*[A-Za-z0-9_-]+:\s+"/m.test(r.frontmatter));
    const withBlockList = realAgentRecords.filter((r) => Object.keys(r.lists).length > 0);
    assert.ok(withQuoted.length > 0, "no real agent carries a quoted scalar, so the quote handling above is untested against the real tree");
    assert.ok(withBlockList.length > 0, "no real agent carries a block list, so the list handling above is untested against the real tree");
  });

  it("falsifiability: the oracle comparison reports a key the line reader refuses (`max_turns : 5` is valid YAML)", () => {
    const found = readerDisagreements("name: a\nmax_turns : 5\ncolor: blue\n");
    assert.deepEqual(found, ["max_turns: yaml sees this key, the reader does not"]);
  });

  it("falsifiability: the oracle comparison reports a value difference (an escape the reader models differently)", () => {
    // yaml reads "\x41" as A; the reader refuses it as malformed and records "" -- reported, not silent.
    const found = readerDisagreements('name: a\ncolor: "\\x41"\n');
    assert.equal(found.length, 1);
    assert.match(found[0], /^color: reader "" vs yaml "A"$/);
  });

  it("a clean generated-shaped block has no disagreement", () => {
    assert.deepEqual(readerDisagreements('# Generated by Covenant 0.1.0.\nname: a\ntools:\n  - Read\n  - Write\nmaxTurns: 6\ncolor: "blue"\n'), []);
  });
});

