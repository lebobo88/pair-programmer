/**
 * Regression guard for the Copilot-mirror comment-stripping defect, updated for the
 * Covenant-generated agent files (pair-programmer #73).
 *
 * HISTORY. scripts/sync-copilot-assets.mjs rebuilds Copilot frontmatter from a whitelist
 * of keys instead of copying the .claude source frontmatter, so YAML comments were
 * silently dropped. The casualty was the rationale above `copilot-model: gpt-5.4` in
 * .claude/agents/pair-programmer-orchestrator.md -- a warning that the Copilot CLI catalog
 * is NOT the `codex exec` catalog and that sweeping the pin with the codex pins reproduces
 * AGY-MODEL-ID-STALE. Anyone reading (or sweeping) the mirror never saw it, and editing the
 * mirror was futile because the next sync overwrote it. The fix re-emitted the comment as an
 * HTML comment in the mirror body.
 *
 * WHAT CHANGED. `.claude/agents/*.md` and `.github/agents/*.agent.md` are now generated by
 * the Covenant compiler (`cov build`) from `covenant/*.cov`. `cov build` does not emit
 * author comments (covenant packages/import/NORMALIZATIONS.md, List 2 item 5); the rationale
 * is a `//` comment in covenant/pair-programmer-orchestrator.cov, directly above the `model`
 * items that `copilot-model` became, and both generated files carry a header naming that
 * source (`# source: pair-programmer-orchestrator.cov`). The agent mirror is no longer a
 * product of the sync script (its removal from the script is pair-programmer #71), so the
 * old checks of "what the sync script wrote into the checked-in agent mirror" cannot hold.
 *
 * WHAT EACH CHECK IS NOW (nothing is dropped without a replacement, AGENTS.md Hard Rule 8):
 *   1. source carries the rationale          -> same substance, read from the .cov source.
 *   2. mirror body carries the rationale     -> replaced by: the mirror names its source, and
 *                                              that source carries the rationale (a reader of
 *                                              the mirror is pointed at it).
 *   3. rationale is an HTML comment in the body, not in the frontmatter
 *                                            -> the "not in the schema-validated frontmatter"
 *                                              half is kept on the checked-in mirror; the
 *                                              "as an HTML comment in the body, after the
 *                                              banner" half asserted the sync script's output
 *                                              for agents and is replaced by driving the
 *                                              script's real preservedFrontmatterComments().
 *   4. payload cannot terminate its comment  -> the real function is driven with the real
 *                                              rationale text plus a hostile terminator
 *                                              (also covered by sync-comment-injection.unit.mjs).
 *   5. mirror still pins gpt-5.4             -> unchanged.
 *
 * Self-contained: pure file reads, no daemon, no dist import.
 */

import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";
import { readFileSync, existsSync } from "node:fs";
import assert from "node:assert/strict";
import { test, describe } from "node:test";

import {
  readFrontmatterFile,
  generatedHeader,
  leadingCommentBlocks,
  splitFrontmatter,
} from "./fixtures/frontmatter-yaml.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..", "..");

const SOURCE = join(ROOT, "covenant", "pair-programmer-orchestrator.cov");
const GENERATED_CLAUDE = join(ROOT, ".claude", "agents", "pair-programmer-orchestrator.md");
const MIRROR = join(ROOT, ".github", "agents", "pair-programmer-orchestrator.agent.md");

const { preservedFrontmatterComments } = await import(
  pathToFileURL(join(ROOT, "scripts", "sync-copilot-assets.mjs")).href
);

const RATIONALE_SENTINEL = "copilot-model is deliberately NOT swept with the codex pins";
const CLOSE = "--" + ">"; // written without a literal terminator in this source

/** The `//` comment block of the .cov source that carries the rationale, or undefined.
 * Pure function of the source text so the falsifiability fixtures call the same code. */
function rationaleBlock(covSource) {
  return leadingCommentBlocks(covSource).find((b) => b.text.includes(RATIONALE_SENTINEL));
}

/** Problems with how the rationale sits in a .cov source; [] means it holds. */
function rationaleProblems(covSource) {
  const block = rationaleBlock(covSource);
  if (!block) return [`no \`//\` comment block carries "${RATIONALE_SENTINEL}"`];
  const problems = [];
  if (!/AGY-MODEL-ID-STALE/.test(block.text)) {
    problems.push("the failure-mode reference AGY-MODEL-ID-STALE is missing from the rationale block, not just a truncated first line");
  }
  // The comment must sit above the item the key became: the run of `model` items that
  // contains the Copilot pin.
  const modelRun = [];
  for (const line of block.followingLines) {
    if (!/^\s*model\b/.test(line)) break;
    modelRun.push(line);
  }
  if (!modelRun.some((l) => /^\s*model\s+copilot\s+"[^"]+"/.test(l))) {
    problems.push(`the rationale is not directly above the \`model\` items that hold the Copilot pin (next lines: ${JSON.stringify(block.followingLines)})`);
  }
  return problems;
}

/** True when the rationale text sits inside the frontmatter block of a mirror. */
function frontmatterCarriesRationale(mirrorContent) {
  return /copilot-model is deliberately/.test(splitFrontmatter(mirrorContent).frontmatter);
}

describe("sync-copilot-assets preserves frontmatter comments", () => {
  test("the Covenant source still carries the copilot-model rationale comment, directly above the copilot model pin", () => {
    assert.ok(existsSync(SOURCE), `${SOURCE} must exist`);
    const problems = rationaleProblems(readFileSync(SOURCE, "utf8"));
    assert.deepEqual(
      problems, [],
      "source rationale comment removed or detached -- if this pin is now safe to sweep, say so explicitly",
    );
  });

  test("the generated .github mirror names its Covenant source, and that source carries the rationale", () => {
    assert.ok(existsSync(MIRROR), `${MIRROR} must exist -- run cov build`);
    const mirror = readFrontmatterFile(MIRROR);
    assert.equal(mirror.found, true, "mirror must have a frontmatter block");
    const header = generatedHeader(mirror.comments);
    assert.equal(header.generated, true, "mirror lost its `# Generated by Covenant` header, so nothing points a reader at the source");
    assert.equal(header.source, "pair-programmer-orchestrator.cov", "mirror header must name the orchestrator's Covenant source");
    const covPath = join(ROOT, "covenant", header.source);
    assert.ok(existsSync(covPath), `${covPath} named by the mirror header must exist`);
    assert.deepEqual(rationaleProblems(readFileSync(covPath, "utf8")), []);
    // The Claude-side generated file points at the same source.
    assert.equal(generatedHeader(readFrontmatterFile(GENERATED_CLAUDE).comments).source, header.source);
  });

  test("the rationale is not injected into the schema-validated Copilot frontmatter", () => {
    const content = readFileSync(MIRROR, "utf8");
    const { frontmatter, found } = splitFrontmatter(content);
    assert.equal(found, true, "mirror must start with a frontmatter fence and have a closing one");
    assert.ok(frontmatter.length > 0, "frontmatter is empty, so the absence check below would pass vacuously");
    assert.equal(
      frontmatterCarriesRationale(content), false,
      "rationale must NOT be injected into the schema-validated Copilot frontmatter",
    );
  });

  test("falsifiability: frontmatterCarriesRationale() fires on a mirror whose frontmatter carries the rationale, and not on one whose body does", () => {
    assert.equal(frontmatterCarriesRationale(`---\n# ${RATIONALE_SENTINEL}\nname: x\n---\nbody\n`), true);
    assert.equal(frontmatterCarriesRationale(`---\nname: x\n---\n<!-- ${RATIONALE_SENTINEL} -->\n`), false);
    assert.equal(frontmatterCarriesRationale(`---\r\n# ${RATIONALE_SENTINEL}\r\nname: x\r\n---\r\nbody\r\n`), true, "CRLF must not hide the rationale from the check");
  });

  test("the script's preservedFrontmatterComments() still emits comments as one HTML comment block (the mechanism the commands mirror uses)", () => {
    const block = rationaleBlock(readFileSync(SOURCE, "utf8"));
    assert.ok(block, "rationale block missing from the source, so there is no real payload to drive");
    const legacyFrontmatter = ["name: x", ...block.lines.map((l) => `# ${l}`), "model: y"].join("\n");
    const out = preservedFrontmatterComments(legacyFrontmatter, ".claude/agents/pair-programmer-orchestrator.md");
    assert.ok(out.startsWith("<!--"), "output must open an HTML comment");
    assert.ok(out.trimEnd().endsWith(CLOSE), "output must close the HTML comment at the end");
    assert.match(out, /copilot-model is deliberately NOT swept with the codex pins/);
    assert.match(out, /AGY-MODEL-ID-STALE/, "the failure-mode reference must survive, not just a truncated first line");
    assert.equal(preservedFrontmatterComments("name: x\nmodel: y", "src.md"), "", "no comments must yield no block, or the check above is a constant");
  });

  test("the real rationale plus a hostile terminator cannot terminate the preserved HTML comment early", () => {
    const block = rationaleBlock(readFileSync(SOURCE, "utf8"));
    assert.ok(block, "rationale block missing from the source");
    const hostile = ["name: x", ...block.lines.map((l) => `# ${l}`), `# trailing ${CLOSE} <script>x</script>`].join("\n");
    const out = preservedFrontmatterComments(hostile, "src.md");
    assert.ok(out.includes("<!--"), "a comment block must have been produced");
    const inner = out.slice(4, out.lastIndexOf(CLOSE));
    assert.ok(
      !inner.includes("--"),
      "a literal '--' inside the payload would close the HTML comment early; it must be neutralised",
    );
    assert.equal(out.split(CLOSE).length - 1, 1, "exactly one terminator, at the end");
  });

  test("the mirror still pins copilot model gpt-5.4", () => {
    const mirror = readFileSync(MIRROR, "utf8");
    assert.match(mirror, /^model:\s*"?gpt-5\.4"?\s*$/m,
      "the Copilot orchestrator pin changed — the preserved rationale says verify against the Copilot CLI first",
    );
  });
});
